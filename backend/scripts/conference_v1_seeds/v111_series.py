from __future__ import annotations


def _mk(
    key: str,
    name: str,
    english: str,
    short: str,
    discipline: str,
    official: str,
    domain: str,
    *,
    organizer: str | list[str] = "ACM",
    source_type: str = "conference_official_site",
    subdiscipline: str | None = None,
    frequency: str | None = "annual",
    scope: str = "international",
    is_international: bool = True,
    organizer_summary: str | None = None,
    description: str | None = None,
    first_year: int | None = None,
    cn_source_name: str | None = None,
    source_note: str | None = None,
    extra_source: dict | None = None,
) -> dict:
    org_names = [organizer] if isinstance(organizer, str) else organizer
    summary = organizer_summary or f"{name} 为{scope}方向学术会议。"
    source_name = cn_source_name or f"{name} 官方网站"
    source = {
        "source_type": source_type,
        "source_name": source_name,
        "source_url": official,
        "official_domain": domain,
        "retrieved_at": "2026-09-06",
    }
    if source_note:
        source["notes"] = source_note
    sources = [source]
    if extra_source:
        sources.append(extra_source)
    return {
        "key": key,
        "name": name,
        "english_name": english,
        "short_name": short,
        "aliases": [short] if short and short not in (name, english) else [],
        "discipline": discipline,
        "subdiscipline": subdiscipline,
        "organizer_summary": summary,
        "official_website": official,
        "first_held_year": first_year,
        "conference_frequency": frequency,
        "conference_scope": scope,
        "is_international": is_international,
        "description": description,
        "organizations": [{"name": org, "role": "organizer"} for org in org_names],
        "sources": sources,
    }


