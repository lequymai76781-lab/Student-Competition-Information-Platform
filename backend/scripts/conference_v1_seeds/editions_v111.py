"""Academic Conference V1.1.1 real ConferenceEdition expansion.

Every Edition below was checked against the official conference page / CFP /
organiser notice listed in ``sources`` during the 2026-09-06 curation pass.
Deadlines and student-facing facts are only recorded when the official page
states them; everything else stays absent (NULL/unknown). Series student tags
are never copied onto an Edition and historical student tracks are never
assumed for a new Edition.
"""

from __future__ import annotations


def _ed(
    series_key: str,
    year: int,
    edition_name: str,
    *,
    start_date: str | None = None,
    end_date: str | None = None,
    country_or_region: str | None = None,
    city: str | None = None,
    venue: str | None = None,
    edition_number: int | None = None,
    edition_status: str = "held",
    edition_official_url: str,
    abstract_deadline: str | None = None,
    paper_deadline: str | None = None,
    poster_deadline: str | None = None,
    workshop_deadline: str | None = None,
    notification_date: str | None = None,
    camera_ready_deadline: str | None = None,
    registration_deadline: str | None = None,
    registration_url: str | None = None,
    call_for_papers_url: str | None = None,
    notes: str | None = None,
    student_value_tags: list[str] | None = None,
    audience: list[str] | None = None,
    participation_details: dict | None = None,
    paper_details: dict | None = None,
    school_relations: list[dict] | None = None,
    sources: list[tuple[str, str, str, str, str | None]],
) -> dict:
    srcs = []
    for source in sources:
        source_type, source_name, source_url, official_domain, source_notes = source
        item = {
            "source_type": source_type,
            "source_name": source_name,
            "source_url": source_url,
            "official_domain": official_domain,
            "retrieved_at": "2026-09-06",
        }
        if source_notes:
            item["notes"] = source_notes
        srcs.append(item)
    return {
        "series_key": series_key,
        "year": year,
        "edition_name": edition_name,
        "edition_number": edition_number,
        "start_date": start_date,
        "end_date": end_date,
        "country_or_region": country_or_region,
        "city": city,
        "venue": venue,
        "edition_status": edition_status,
        "edition_official_url": edition_official_url,
        "abstract_deadline": abstract_deadline,
        "paper_deadline": paper_deadline,
        "poster_deadline": poster_deadline,
        "workshop_deadline": workshop_deadline,
        "notification_date": notification_date,
        "camera_ready_deadline": camera_ready_deadline,
        "registration_deadline": registration_deadline,
        "registration_url": registration_url,
        "call_for_papers_url": call_for_papers_url,
        "notes": notes,
        "student_value_tags": student_value_tags,
        "audience": audience,
        "participation_details": participation_details,
        "paper_details": paper_details,
        "school_relations": school_relations or [],
        "sources": srcs,
    }


